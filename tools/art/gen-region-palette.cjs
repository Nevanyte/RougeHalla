#!/usr/bin/env node
// Generates client-unity/UnityProject/Assets/Scripts/View/Regions/RegionPaletteGenerated.cs from docs/art/palette.json so the
// Unity region themes never hand-copy colours. OKLCH -> sRGB uses the same formulas as tools/art/palette-check.cjs
// (Ottosson 2020, gamut-clamped, rounded to 8 bit).
//
//   node tools/art/gen-region-palette.cjs           write the C# file
//   node tools/art/gen-region-palette.cjs --check   exit 1 if the committed C# file is stale (also run by the EditMode test's docs)
'use strict';
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..', '..');
const palettePath = path.join(root, 'docs/art/palette.json');
const outPath = path.join(root, 'client-unity/UnityProject/Assets/Scripts/View/Regions/RegionPaletteGenerated.cs');

// Index in the generated arrays equals the wire region id (0 none -> neutral, uses the coliseum entry).
const REGION_ORDER = ['coliseum', 'fire', 'sentenced', 'plague', 'frost', 'holy', 'coliseum'];
const SLOTS = [
  ['Base', r => r.swatches.base.oklch],
  ['Secondary', r => r.swatches.secondary.oklch],
  ['Accent', r => r.swatches.accent.oklch],
  ['Key', r => r.light.key],
  ['Ambient', r => r.light.ambient],
  ['Shadow', r => r.light.shadow],
  ['Fog', r => r.light.fog],
];

const clamp = v => Math.min(1, Math.max(0, v));
const srgb = v => v <= 0.0031308 ? 12.92 * v : 1.055 * Math.pow(v, 1 / 2.4) - 0.055;
function oklchToRgb8([L, C, h]) {
  const hr = h * Math.PI / 180, a = C * Math.cos(hr), b = C * Math.sin(hr);
  const l = (L + .3963377774 * a + .2158037573 * b) ** 3;
  const m = (L - .1055613458 * a - .0638541728 * b) ** 3;
  const s = (L - .0894841775 * a - 1.2914855480 * b) ** 3;
  const lin = [
    4.0767416621 * l - 3.3077115913 * m + .2309699292 * s,
    -1.2684380046 * l + 2.6097574011 * m - .3413193965 * s,
    -.0041960863 * l - .7034186147 * m + 1.7076147010 * s,
  ];
  return lin.map(v => Math.round(srgb(clamp(v)) * 255));
}

function generate() {
  const palette = JSON.parse(fs.readFileSync(palettePath, 'utf8'));
  const f = n => Number(n.toFixed(4)).toString() + 'f';
  const lines = [];
  lines.push('// <auto-generated>');
  lines.push('// Generated by tools/art/gen-region-palette.cjs from docs/art/palette.json. Do not edit by hand:');
  lines.push('// run `node tools/art/gen-region-palette.cjs` after changing the palette. RegionPaletteTests checks the values.');
  lines.push('// </auto-generated>');
  lines.push('using UnityEngine;');
  lines.push('');
  lines.push('namespace Roguehalla.Client');
  lines.push('{');
  lines.push('    /// <summary>Region colours straight from docs/art/palette.json. Row index = wire region id (0 none uses the coliseum entry).</summary>');
  lines.push('    public static class RegionPaletteGenerated');
  lines.push('    {');
  lines.push('        public const int Base = 0, Secondary = 1, Accent = 2, Key = 3, Ambient = 4, Shadow = 5, Fog = 6, SlotCount = 7;');
  lines.push('        /// <summary>Source OKLCH (L, C, h degrees) per [region][slot].</summary>');
  lines.push('        public static readonly float[][][] Oklch =');
  lines.push('        {');
  REGION_ORDER.forEach((name, id) => {
    const r = palette.regions[name];
    lines.push(`            new[] { // ${id} ${name}`);
    SLOTS.forEach(([slot, get]) => { const v = get(r); lines.push(`                new[] { ${f(v[0])}, ${f(v[1])}, ${f(v[2])} }, // ${slot}`); });
    lines.push('            },');
  });
  lines.push('        };');
  lines.push('        /// <summary>sRGB 8-bit per [region][slot], derived from <see cref="Oklch"/>.</summary>');
  lines.push('        public static readonly Color32[][] Srgb =');
  lines.push('        {');
  REGION_ORDER.forEach((name, id) => {
    const r = palette.regions[name];
    lines.push(`            new[] { // ${id} ${name}`);
    SLOTS.forEach(([slot, get]) => {
      const [R, G, B] = oklchToRgb8(get(r));
      lines.push(`                new Color32(${R}, ${G}, ${B}, 255), // ${slot}`);
    });
    lines.push('            },');
  });
  lines.push('        };');
  lines.push('    }');
  lines.push('}');
  return lines.join('\n') + '\n';
}

const text = generate();
if (process.argv.includes('--check')) {
  const have = fs.existsSync(outPath) ? fs.readFileSync(outPath, 'utf8') : '';
  if (have !== text) { console.error('RegionPaletteGenerated.cs is stale: run node tools/art/gen-region-palette.cjs'); process.exit(1); }
  console.log('RegionPaletteGenerated.cs matches docs/art/palette.json');
} else {
  fs.mkdirSync(path.dirname(outPath), { recursive: true });
  fs.writeFileSync(outPath, text);
  console.log('wrote ' + path.relative(root, outPath));
}
