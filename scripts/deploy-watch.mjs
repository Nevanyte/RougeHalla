#!/usr/bin/env node
// macOS schedules a bounded main-branch check; the deploy command owns rollout, health and rollback.
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { spawn, spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import { validateConfig } from "./deploy-lib.mjs";

export const LABEL = "com.rougehalla.autodeploy";
const HERE = path.dirname(fileURLToPath(import.meta.url));
const MARKER = "Generated by RougeHalla deploy-watch";
const xml = (value) => String(value).replaceAll("&", "&amp;").replaceAll("<", "&lt;").replaceAll(">", "&gt;").replaceAll('"', "&quot;").replaceAll("'", "&apos;");

export function parseWatchArgs(argv) {
  const args = { command: "status", config: path.join(os.homedir(), ".rougehalla", "deploy-config.json"), interval: 60 };
  let command = false;
  for (let i = 0; i < argv.length; i++) {
    const part = argv[i];
    if (["once", "install", "uninstall", "status"].includes(part) && !command) { args.command = part; command = true; }
    else if (part === "--config") {
      const value = argv[++i];
      if (!value || value.startsWith("--")) throw new Error("--config requires a path");
      args.config = path.resolve(value);
    } else if (part === "--interval") {
      const value = argv[++i];
      if (!/^\d+$/.test(value ?? "") || Number(value) < 30 || Number(value) > 3600) throw new Error("--interval must be 30–3600 seconds");
      args.interval = Number(value);
    } else if (part === "--help" || part === "-h") args.command = "help";
    else throw new Error(`Unknown watch argument: ${part}`);
  }
  return args;
}

export function launchAgentPlist({ node, runtime, config, stateDir, interval }) {
  const search = [...new Set([path.dirname(node), "/opt/homebrew/bin", "/usr/local/bin", "/usr/bin", "/bin", "/usr/sbin", "/sbin"])].join(":");
  return `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<!-- ${MARKER}. Disable with npm run deploy:auto:stop. -->
<plist version="1.0"><dict>
<key>Label</key><string>${LABEL}</string>
<key>ProgramArguments</key><array><string>${xml(node)}</string><string>${xml(path.join(runtime, "deploy-watch.mjs"))}</string><string>once</string><string>--config</string><string>${xml(config)}</string></array>
<key>WorkingDirectory</key><string>${xml(stateDir)}</string>
<key>EnvironmentVariables</key><dict><key>PATH</key><string>${xml(search)}</string><key>GIT_TERMINAL_PROMPT</key><string>0</string></dict>
<key>RunAtLoad</key><true/>
<key>StartInterval</key><integer>${interval}</integer>
<key>ProcessType</key><string>Background</string>
<key>LowPriorityIO</key><true/>
<key>StandardOutPath</key><string>${xml(path.join(stateDir, "deploy-auto.log"))}</string>
<key>StandardErrorPath</key><string>${xml(path.join(stateDir, "deploy-auto.log"))}</string>
</dict></plist>
`;
}

function settings(configPath) {
  if (!fs.existsSync(configPath)) throw new Error(`Create ${configPath} first; see README, Automatic live updates.`);
  if (fs.statSync(configPath).mode & 0o077) throw new Error("Deployment config must have mode 0600");
  return validateConfig(JSON.parse(fs.readFileSync(configPath, "utf8")));
}

function runningDeployment(stateDir) {
  const lock = path.join(stateDir, "deploy.lock");
  if (!fs.existsSync(lock)) return false;
  // Conservatively preserve a lock whose format this installer does not recognize.
  return true;
}

function launchctl(args, optional = false) {
  const result = spawnSync("/bin/launchctl", args, { encoding: "utf8" });
  if (result.error || result.status !== 0) {
    if (optional) return false;
    throw new Error(`launchctl ${args[0]} failed: ${(result.stderr || result.error?.message || "unknown error").trim()}`);
  }
  return true;
}

export async function runWatch(args) {
  if (args.command === "help") {
    console.log("Usage: node scripts/deploy-watch.mjs [install|uninstall|status|once] [--config PATH] [--interval 60]\ninstall: enable automatic main deployments on this Mac; uninstall: disable them. once: perform one guarded check.");
    return 0;
  }
  const config = settings(args.config);
  if (args.command === "once") {
    return await new Promise((resolve) => {
      const child = spawn(config.nodeBinary || process.execPath, [path.join(HERE, "deploy.mjs"), "deploy", "--config", args.config], {
        stdio: "inherit", env: { ...process.env, GIT_TERMINAL_PROMPT: "0" },
      });
      child.once("error", (error) => { console.error(`[autodeploy] ${error.message}`); resolve(1); });
      child.once("exit", (code) => resolve(code ?? 1));
    });
  }
  if (process.platform !== "darwin") throw new Error("Automatic installation uses macOS launchd; deploy and once work on other hosts.");
  const domain = `gui/${process.getuid()}`;
  const target = `${domain}/${LABEL}`;
  const file = path.join(os.homedir(), "Library", "LaunchAgents", `${LABEL}.plist`);
  if (args.command === "status") {
    const installed = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : "";
    const interval = installed.includes(MARKER) ? Number(installed.match(/<key>StartInterval<\/key>\s*<integer>(\d+)<\/integer>/)?.[1]) : null;
    console.log(JSON.stringify({ enabled: launchctl(["print", target], true), intervalSeconds: interval,
      config: args.config, log: path.join(config.stateDir, "deploy-auto.log") }, null, 2));
    return 0;
  }
  if (runningDeployment(config.stateDir)) throw new Error("A deployment lock exists. Let that deployment finish before changing automatic updates.");
  if (fs.existsSync(file) && !fs.readFileSync(file, "utf8").includes(MARKER)) throw new Error("Refusing to replace an unrecognized launch agent");
  if (args.command === "uninstall") {
    launchctl(["bootout", target], true);
    if (fs.existsSync(file)) fs.unlinkSync(file);
    console.log("[autodeploy] Disabled. The live game server keeps running.");
    return 0;
  }
  const runtime = path.join(config.stateDir, "deployer");
  fs.mkdirSync(runtime, { recursive: true, mode: 0o700 });
  for (const name of ["deploy.mjs", "deploy-lib.mjs", "deploy-watch.mjs"]) {
    const source = path.join(HERE, name), destination = path.join(runtime, name);
    if (path.resolve(source) === path.resolve(destination)) continue;
    const temp = `${destination}.${process.pid}.tmp`;
    fs.copyFileSync(source, temp);
    fs.chmodSync(temp, 0o600);
    fs.renameSync(temp, destination);
  }
  const stableNode = config.nodeBinary || (fs.existsSync("/opt/homebrew/bin/node") ? "/opt/homebrew/bin/node" : process.execPath);
  const plist = launchAgentPlist({ node: stableNode, runtime, config: args.config, stateDir: config.stateDir, interval: args.interval });
  fs.mkdirSync(path.dirname(file), { recursive: true });
  launchctl(["bootout", target], true);
  fs.writeFileSync(file, plist, { mode: 0o600 });
  launchctl(["bootstrap", domain, file]);
  console.log(`[autodeploy] Enabled: checking ${config.branch || "main"} every ${args.interval}s. Log: ${path.join(config.stateDir, "deploy-auto.log")}`);
  return 0;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try { process.exitCode = await runWatch(parseWatchArgs(process.argv.slice(2))); }
  catch (error) { console.error(`[autodeploy] ${error.message}`); process.exitCode = 1; }
}
