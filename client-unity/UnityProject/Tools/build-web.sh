#!/usr/bin/env bash
# Bake the authoritative server's exact content identity before Unity compiles the player.
set -euo pipefail
project="$(cd "$(dirname "$0")/.." && pwd)"
info_url="${RH_SERVER_INFO_URL:-http://127.0.0.1:7777/info}"
python3 - "$info_url" "$project/Assets/Scripts/BakedContent.cs" <<'PY'
import json, pathlib, re, sys, urllib.request
with urllib.request.urlopen(sys.argv[1], timeout=10) as response:
    info = json.load(response)
raw = info.get('contentHash')
if not isinstance(raw, str) or not re.fullmatch(r'[0-9a-fA-F]{16}', raw):
    raise SystemExit('/info must contain contentHash as exactly 16 hexadecimal digits')
value = int(raw, 16)
if value == 0:
    raise SystemExit('Refusing zero content hash')
source = ('// Generated by Tools/build-web.sh from the Rust server /info contentHash.\n'
          'namespace Roguehalla.Client\n{\n    public static class BakedContent\n    {\n'
          f'        public const ulong Hash = 0x{value:016x}UL;\n    }}\n}}\n')
path = pathlib.Path(sys.argv[2])
if not path.exists() or path.read_text() != source:
    path.write_text(source)
print(f'Baked authoritative content hash {value:016x}')
PY
if [[ "${1:-}" == "--prepare-only" ]]; then exit 0; fi
# Resolve the exact installed Editor without changing licenses or installing anything.
unity_editor="${RH_UNITY_EDITOR:-}"
if [[ -z "$unity_editor" ]]; then
    unity_editor="$(python3 - "$project" <<'PYEDITOR'
import json, pathlib, subprocess, sys
project = pathlib.Path(sys.argv[1])
version = next(line.split(':', 1)[1].strip() for line in
               (project / 'ProjectSettings/ProjectVersion.txt').read_text().splitlines()
               if line.startswith('m_EditorVersion:'))
result = json.loads(subprocess.check_output(['unity', 'editors', '--installed', '--format', 'json']))
if not result.get('success'):
    raise SystemExit('Cannot list installed Editors')
editors = result['data']['items'] if isinstance(result['data'], dict) else result['data']
match = next((e for e in editors if e['version'] == version), None)
if match is None:
    raise SystemExit(f'Install Unity {version} with Web Build Support first')
location = pathlib.Path(match['location'])
if location.suffix == '.app':
    location = location / 'Contents/MacOS/Unity'
elif (location / 'Editor/Unity').is_file():
    location = location / 'Editor/Unity'
elif (location / 'Unity.exe').is_file():
    location = location / 'Unity.exe'
print(location)
PYEDITOR
)"
fi
build_log="${RH_UNITY_BUILD_LOG:-$project/Logs/web-build.log}"
mkdir -p "$(dirname "$build_log")"
echo "Building Web player; log: $build_log"
"$unity_editor" -batchmode -quit -projectPath "$project" -buildTarget WebGL \
    -executeMethod Roguehalla.Editor.RhBuild.BuildWeb -logFile "$build_log" "$@"
# A project shader that fails to compile for the Web target is silently replaced by nothing in the player ("shader is not
# supported on this GPU" in the browser console), so the effect just vanishes. Fail the build instead.
if grep -E "Shader error in 'Roguehalla/" "$build_log"; then
    echo "error: a Roguehalla shader failed to compile for WebGL (see the lines above and $build_log)" >&2
    exit 1
fi
# Keep imported font/resource notices with the distributable player.
mkdir -p "$project/Build/Web/Licenses"
cp "$project/../../LICENSE" "$project/Build/Web/Licenses/Roguehalla-MIT.txt"
cp "$project/Assets/TextMesh Pro/License.Unity.md" "$project/Build/Web/Licenses/Unity-Companion.md"
cp "$project/Assets/TextMesh Pro/Fonts/LiberationSans - OFL.txt" "$project/Build/Web/Licenses/LiberationSans-OFL.txt"
cp "$project/Assets/TextMesh Pro/Sprites/EmojiOne Attribution.txt" "$project/Build/Web/Licenses/EmojiOne-Attribution.txt"
# Every required third-party notice ships with the player (docs/art/LICENCE_LEDGER.md, "Build notices"). RhBuild.CopyNotices
# already copies the MIT, Flare base, Cinzel and THIRD_PARTY files; this adds the notices it lacks (Flare expansions) and
# then fails if any required file is absent: a licence notice that cannot be shipped must not be skipped silently.
third_party="$project/Assets/Art/ThirdParty"
licenses="$project/Build/Web/Licenses"
add_notice() { cp "$third_party/$1" "$licenses/$2"; }
add_notice Fonts/OFL-CinzelDecorative.txt CinzelDecorative-OFL.txt
add_notice FlareExpansion/LICENSE.txt FlareExpansion-LICENSE.txt
add_notice FlareExpansion/CREDITS.md FlareExpansion-CREDITS.md
add_notice FlareExpansion/CREDITS_CAPTURE.txt FlareExpansion-CREDITS_CAPTURE.txt
add_notice FlareProps/Raw/LICENSE.txt FlareProps-LICENSE.txt
add_notice FlareProps/Raw/CREDITS_CAPTURE.txt FlareProps-CREDITS_CAPTURE.txt
add_notice FlareAudioExpansion/LICENSE.txt FlareAudioExpansion-LICENSE.txt
add_notice FlareAudioExpansion/CREDITS_CAPTURE.txt FlareAudioExpansion-CREDITS_CAPTURE.txt
for required in Roguehalla-MIT.txt Unity-Companion.md LiberationSans-OFL.txt EmojiOne-Attribution.txt CinzelDecorative-OFL.txt \
    Flare-CC-BY-SA-3.0.txt Flare-Credits.txt Flare-Audio-Notice.txt Third-Party-Assets.md FlareExpansion-LICENSE.txt \
    FlareExpansion-CREDITS.md FlareProps-LICENSE.txt FlareAudioExpansion-LICENSE.txt; do
    [[ -s "$licenses/$required" ]] || { echo "Missing required licence notice: $required" >&2; exit 1; }
done
# Every streamed audio file the client requests (ids in RegionAtmosphereTable.AllAudioIds) must sit where the player fetches it.
for id in $(sed -n '/AllAudioIds/,/};/p' "$project/Assets/Scripts/View/Atmosphere/RegionAtmosphereTable.cs" | grep -o '"[a-z_]*"' | tr -d '"'); do
    [[ -s "$project/Build/Web/StreamingAssets/Audio/$id.mp3" ]] || { echo "BUILD CHECK FAILED: Build/Web/StreamingAssets/Audio/$id.mp3 is missing" >&2; exit 1; }
done
echo "Audio check: all streamed files present"
