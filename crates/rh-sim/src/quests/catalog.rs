//! Source `shared/quests.ts` `QUEST_DEFS`: the twenty K1 quest offers as typed rows (content §6A). The closed verb model
//! is [`Kind`]; optional objective modifiers are plain fields, never free text. Rows are registered as the `quests/1`
//! content table, so a rule cannot influence a match without moving the rules identity.
use crate::cards::CardId;
use crate::FactionId;

/// Source `QuestKind`: the closed verb set (kill / collect / fetch).
#[derive(Clone, Copy, Debug, PartialEq, Eq, serde::Serialize, serde::Deserialize)]
pub enum Kind {
    Kill,
    Collect,
    Fetch,
}
impl Kind {
    pub const ALL: [Self; 3] = [Self::Kill, Self::Collect, Self::Fetch];
    pub const fn index(self) -> usize {
        self as usize
    }
    pub const fn as_str(self) -> &'static str {
        match self {
            Self::Kill => "kill",
            Self::Collect => "collect",
            Self::Fetch => "fetch",
        }
    }
}

/// Source collect token placement: the region's farthest camp, the outer starts, or the middle camps.
#[derive(Clone, Copy, Debug, PartialEq, Eq, serde::Serialize, serde::Deserialize)]
pub enum Tokens {
    Camp,
    Rim,
    Mid,
}
impl Tokens {
    pub const fn code(self) -> u8 {
        match self {
            Self::Camp => 1,
            Self::Rim => 2,
            Self::Mid => 3,
        }
    }
}

