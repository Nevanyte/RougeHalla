pub fn by_id(id: &str) -> Option<&'static Def> {
    DEFINITION.iter().find(|d| d.id == id)
}

/// Folds the catalog into the rules identity (the `quests/1` content table).
pub fn visit_content(mut word: impl FnMut(u64)) {
    word(DEFINITION.len() as u64);
    for d in DEFINITION {
        for text in [d.id, d.name, d.giver, d.text] {
            word(text.len() as u64);
            for b in text.bytes() {
                word(u64::from(b));
            }
        }
        word(d.kind.index() as u64);
        word(d.count as u64);
        word(d.region.map_or(0, |f| u64::from(f.code()) + 1));
        word(u64::from(d.far_zone.code()));
        word(u64::from(d.elite));
        word(u64::from(d.players));
        word(d.tour as u64);
        word(d.tokens.map_or(0, |t| u64::from(t.code())));
        word(d.token_spawns as u64);
        word(d.obj_sec.to_bits());
        word(d.travel_sec.to_bits());
        word(d.reward_card.index() as u64);
        word(d.reward_copies as u64);
        word(u64::from(d.reward_gv));
        word(d.expires_at_sec.to_bits());
    }
    // Stage0 domain revision: the tour-supply rule now consumes the stored visit mask, not its population count.
    // Keep the twenty catalog rows and every preexisting fold word unchanged; append one text marker below.
    let marker = "tour-supply/visited-region-mask/1";
    word(marker.len() as u64);
    for b in marker.bytes() {
        word(u64::from(b));
    }
}
