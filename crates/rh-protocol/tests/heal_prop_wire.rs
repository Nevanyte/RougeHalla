//! P-COLISEUM-HEALS-2 oracle (wire): a coliseum heal pickup is a State key 2 prop row of kind 8 with the cannon's layout,
//! `handle varint | x u16 | y u16 | 8 u8 | ready_at varint` (server ms it is available again; 0 now), at protocol 20.
//! Every other prop kind keeps its bytes; any kind byte past 8 is still refused ("prop kind"). The golden vectors
//! `state_heal_props` (server) carries it to the C# and JS decoders.
use rh_protocol::samples::server_samples;
use rh_protocol::{
    DecodeError, PickupHandle, ServerMsg, StateItem, WireProp, WirePropKind, WireProps, Writer,
    PROTOCOL_VERSION,
};

/// The four pickup positions in 1/8 units (tile centres 2544 and 2576 sim units), NW, NE, SW, SE.
const SPOTS: [(u16, u16); 4] = [
    (20352, 20352),
    (20608, 20352),
    (20352, 20608),
    (20608, 20608),
];

fn heal(handle: u32, (x, y): (u16, u16), ready_at: u32) -> WireProp {
    WireProp {
        handle: PickupHandle::new(handle).unwrap(),
        x,
        y,
        kind: WirePropKind::Heal { ready_at },
    }
}

/// The rows of the `state_heal_props` vector (the brief, §4).
fn vector_rows() -> Vec<WireProp> {
    vec![
        heal(1, SPOTS[0], 0),
        heal(2, SPOTS[1], 30_000),
        heal(3, SPOTS[2], u32::MAX),
        heal(4, SPOTS[3], 0),
    ]
}

fn state(tick: u32, rows: Vec<WireProp>) -> ServerMsg {
    ServerMsg::State {
        tick,
        items: vec![StateItem::Props(WireProps { rows, focus: None })],
    }
}

/// Hand-written reference encoder (the spec): a State frame with key 2 and these rows, each `(handle, x, y, kind byte,
/// raw payload)`, and no focus.
fn frame(tick: u32, rows: &[(u32, u16, u16, u8, Vec<u8>)]) -> Vec<u8> {
    let mut w = Writer::default();
    w.u8(0x88);
    w.varint(tick);
    w.varint(1);
    w.varint(2);
    w.varint(rows.len() as u32);
    for (handle, x, y, kind, payload) in rows {
        w.varint(*handle);
        w.u16(*x);
        w.u16(*y);
        w.u8(*kind);
        w.bytes(payload);
    }
    w.varint(0);
    w.finish()
}

fn varint(v: u32) -> Vec<u8> {
    let mut w = Writer::default();
    w.varint(v);
    w.finish()
}

#[test]
fn the_protocol_is_22() {
    assert_eq!(
        PROTOCOL_VERSION, 22,
        "a new prop kind is an incompatible wire change: 19 -> 20 (origin); P-SYNC-ORIGIN-2 carries it as 22"
    );
}

#[test]
fn a_heal_row_is_the_cannon_layout_with_kind_8() {
    let msg = state(202, vector_rows());
    let want = frame(
        202,
        &[
            (1, SPOTS[0].0, SPOTS[0].1, 8, varint(0)),
            (2, SPOTS[1].0, SPOTS[1].1, 8, varint(30_000)),
            (3, SPOTS[2].0, SPOTS[2].1, 8, varint(u32::MAX)),
            (4, SPOTS[3].0, SPOTS[3].1, 8, varint(0)),
        ],
    );
    assert_eq!(msg.encode(), want, "the bytes of the brief's layout");
    assert_eq!(ServerMsg::decode(&want), Ok(msg), "and they decode back");

    // The same row as a cannon differs only in the kind byte.
    let cannon = state(
        202,
        vec![WireProp {
            kind: WirePropKind::Cannon { ready_at: 30_000 },
            ..heal(2, SPOTS[1], 30_000)
        }],
    )
    .encode();
    let healed = state(202, vec![heal(2, SPOTS[1], 30_000)]).encode();
    assert_eq!(cannon.len(), healed.len());
    let differ: Vec<(u8, u8)> = cannon
        .iter()
        .zip(&healed)
        .filter(|(a, b)| a != b)
        .map(|(a, b)| (*a, *b))
        .collect();
    assert_eq!(differ, vec![(6, 8)], "only the kind byte: cannon 6, heal 8");
}

#[test]
fn unknown_prop_kinds_are_still_refused() {
    for kind in [0u8, 9, 255] {
        let bytes = frame(202, &[(1, 80, 160, kind, varint(0))]);
        assert_eq!(
            ServerMsg::decode(&bytes),
            Err(DecodeError::BadField("prop kind")),
            "prop kind {kind}"
        );
    }
}

#[test]
fn the_golden_vectors_carry_the_heal_props_and_the_unknown_kind() {
    let msg = server_samples()
        .into_iter()
        .find(|(name, _)| *name == "state_heal_props")
        .map(|(_, m)| m);
    assert_eq!(
        msg,
        Some(state(202, vector_rows())),
        "a server vector state_heal_props (samples.rs) holds the brief's rows"
    );
    // Hand-built rather than a shared malformed vector (tools/protocol-js/check-vectors.mjs is provenance-pinned):
    // one prop row of kind 9, past the heal's 8.
    let bad: &[u8] = &[0x88, 0xca, 0x01, 1, 2, 1, 1, 0x50, 0, 0xa0, 0, 9, 0, 0];
    assert_eq!(
        ServerMsg::decode(bad),
        Err(DecodeError::BadField("prop kind")),
        "an unknown prop kind (9) is refused for its prop kind"
    );

    // The committed fixture holds both (regenerated by `cargo run -p rh-protocol --bin protocol-fixtures`).
    let path = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../../protocol/fixtures")
        .join(format!("v{PROTOCOL_VERSION}.json"));
    let committed = std::fs::read_to_string(&path).expect("the committed fixture");
    assert!(
        committed.contains("\"state_heal_props\""),
        "state_heal_props is in the committed v{PROTOCOL_VERSION}.json"
    );
}

/// Guard (green today): the other kinds keep their bytes (the `state_union_props` vector).
#[test]
fn guard_the_union_props_vector_keeps_its_bytes() {
    let (_, msg) = server_samples()
        .into_iter()
        .find(|(name, _)| *name == "state_union_props")
        .unwrap();
    assert_eq!(
        msg.encode(),
        frame(
            201,
            &[
                (1, 80, 160, 4, [&[6u8][..], b"fallen"].concat()),
                (2, 81, 161, 5, Vec::new()),
                (3, 82, 162, 6, varint(u32::MAX)),
            ]
        )
    );
}
